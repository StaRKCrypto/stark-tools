/** Airport stations for daily-max weather markets. Coords = resolution airport, not city center. */
export type TempUnit = 'C' | 'F'
export type StationRegion = 'us' | 'eu' | 'asia' | 'latam' | 'oceania' | 'africa'

export type ResolutionSource = 'noaa' | 'wu' | 'hko'
export type RoundingMode = 'whole' | 'one_decimal'
export type PrimaryFetch =
  | 'synoptic_madis'
  | 'hko_daily_extract'
  | 'wu_daily_observations'

export interface Station {
  slug: string
  city: string
  icao: string
  stationName: string
  lat: number
  lon: number
  timezone: string
  unit: TempUnit
  biasC: number
  peakHour: number
  region: StationRegion
  /** When false, do not lock YES on METAR print (HK Observatory ≠ VHHH). */
  metarIsResolution?: boolean
  note?: string
  /** Polymarket resolution feed (NOAA WRH / WU / HKO). */
  resolutionSource?: ResolutionSource
  resolutionStationId?: string
  officialUrl?: string
  rounding?: RoundingMode
  primaryFetch?: PrimaryFetch
  climateClass?: string
  /** True for WU/HKO — METAR must not authorize lock-YES. */
  sourceRisk?: boolean
}

