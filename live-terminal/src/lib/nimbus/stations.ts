export const STATIONS_BY_SLUG: Record<string, Station> = Object.fromEntries(
  STATIONS.map((s) => [s.slug, s]),
)

export const STATIONS_BY_ICAO: Record<string, Station> = Object.fromEntries(
  STATIONS.map((s) => [s.icao, s]),
)

export function findStationByCityHint(hint: string): Station | undefined {
  const h = hint
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
  if (STATIONS_BY_SLUG[h]) return STATIONS_BY_SLUG[h]
  return STATIONS.find(
    (s) =>
      s.slug === h ||
      s.city.toLowerCase() === hint.toLowerCase() ||
      s.slug.includes(h) ||
      h.includes(s.slug),
  )
}

export function stationResolutionId(station: Station): string {
  return (station.resolutionStationId || station.icao).toUpperCase()
}

export function stationSourceRisk(station: Station): boolean {
  if (station.sourceRisk) return true
  if (station.metarIsResolution === false) return true
  const src = station.resolutionSource
  return src === 'wu' || src === 'hko'
}

